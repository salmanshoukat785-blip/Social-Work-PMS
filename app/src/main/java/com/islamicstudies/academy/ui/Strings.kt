val LocalAppLanguage = staticCompositionLocalOf { "ur" }

@Composable
fun screenTitleStyle(): TextStyle =
    if (LocalAppLanguage.current == "ur") UrduText.title else MaterialTheme.typography.titleLarge

/** Picks the title to show first: English only when the app is in English and an English title exists. */
fun pickTitle(ur: String, en: String, language: String): String =
    if (language == "en" && en.isNotBlank()) en else ur

fun isEnglishPrimary(en: String, language: String): Boolean = language == "en" && en.isNotBlank()
